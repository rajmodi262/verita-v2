"""Generated documents and the honesty scan."""

from __future__ import annotations

import json

import pytest

from verita.pipeline.config import REPO_ROOT
from verita.reports import docs
from verita.reports.honesty import scan, scan_text

METRICS = REPO_ROOT / "reports" / "metrics.json"


@pytest.fixture(scope="module")
def metrics():
    if not METRICS.exists():
        pytest.skip("reports/metrics.json not built")
    return json.loads(METRICS.read_text(encoding="utf-8"))


def test_committed_documents_match_the_committed_metrics(metrics):
    stale = [
        t.name
        for t, text in docs.rendered(metrics).items()
        if t.read_text(encoding="utf-8") != text
    ]
    assert not stale, f"run `verita report build`: {stale}"


def test_rendering_is_deterministic(metrics):
    assert docs.render_eval_report(metrics) == docs.render_eval_report(metrics)
    assert "Generated by `verita report build`" in docs.render_model_card(metrics)


def test_every_headline_figure_is_sourced(metrics):
    assert metrics["headline"]
    for h in metrics["headline"]:
        assert {"key", "label", "value", "dataset", "split", "source"} <= set(h), h
        if h.get("low") is not None:
            assert h["low"] <= h["value"] <= h["high"], h


def test_formatters():
    assert docs.pct(0.50269) == "50.3%"
    assert docs.ci({"value": 0.5, "low": 0.4, "high": 0.6}) == "50.0% (40.0%–60.0%)"
    assert docs.ci({"value": 0.002, "low": None}, "num", 4) == "0.0020"
    assert docs.ci(None) == "—"
    assert docs.count(3047007) == "3,047,007"


def test_splice_replaces_only_the_block():
    readme = f"intro\n{docs.START}\nold\n{docs.END}\noutro\n"
    assert docs.splice_readme(readme, "new\n") == f"intro\n{docs.START}\nnew\n{docs.END}\noutro\n"
    with pytest.raises(ValueError, match="markers"):
        docs.splice_readme("no markers", "x")


@pytest.mark.parametrize(
    ("line", "flagged"),
    [
        ("Our recall is 0.87 on the test set.", True),
        ("F1 of 50.3% beats the rules.", True),
        ("Precision 63 % at the threshold.", True),
        ("Expected recall (95% interval)", False),
        ("Static recall (95% CI)", False),
        ("Realised recall at a 95% guarantee", False),
        ("Was the 95% recall guarantee kept?", False),
        ("Recall is measured on the test split.", False),
        ("Version 0.12 of the recall module", True),  # conservative: decimals near metric words
        ("We review 25% of alerts.", False),  # no metric word
    ],
)
def test_scan_rules(line, flagged):
    assert bool(scan_text(line)) is flagged


def test_generated_regions_are_skipped():
    block = f"{docs.START}\nF1 50.3%\n{docs.END}\n"
    assert scan_text(block) == []
    assert scan_text(f"{docs.BANNER}\nrecall 0.9\n") == []
    assert scan_text(f"{block}after: recall 0.9\n") == [(4, "after: recall 0.9")]


def test_repository_has_no_hand_typed_metrics():
    findings = scan()
    assert not findings, "\n".join(map(str, findings))
