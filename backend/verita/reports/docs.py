def pct(x: float | None, digits: int = 1) -> str:
    return "—" if x is None else f"{x * 100:.{digits}f}%"


def num(x: float | None, digits: int = 3) -> str:
    return "—" if x is None else f"{x:.{digits}f}"


def count(x: int | None) -> str:
    return "—" if x is None else f"{x:,}"


def ci(d: dict[str, Any] | None, fmt: str = "pct", digits: int = 1) -> str:
    if not d or d.get("value") is None:
        return "—"
    f = pct if fmt == "pct" else num
    if d.get("low") is None:
        return f(d["value"], digits)
    return f"{f(d['value'], digits)} ({f(d['low'], digits)}–{f(d['high'], digits)})"


def _env() -> Environment:
    # Markdown output, not HTML: autoescaping would corrupt it.
    env = Environment(undefined=StrictUndefined, trim_blocks=True, lstrip_blocks=True)  # noqa: S701  # nosec B701
    env.filters.update(pct=pct, num=num, ci=ci, count=count)
    return env


