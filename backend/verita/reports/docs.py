def _context(m: dict[str, Any]) -> dict[str, Any]:
    d = m["datasets"][m["primary_dataset"]]
    ctx: dict[str, Any] = {"m": m, "d": d, "banner": BANNER}
    detect = d.get("detect")
    if detect:
        ctx["champ"] = detect["models"]["lgbm_champion"]["test"]
        ctx["bulk"] = detect["models"]["lgbm_champion"].get("test_bulk") or {}
        ctx["rules"] = detect["models"]["rules_incumbent"]["test"]
        ctx["paper"] = detect["published_baselines"]["rows"].get(
            "GFP + LightGBM", {"mean": 0, "std": 0}
        )
        named = [t for t in detect["per_typology"] if t["typology"] != "UNATTRIBUTED"]
        ctx["worst"] = min(named, key=lambda t: t["recall"]["value"])
        ctx["best"] = max(named, key=lambda t: t["recall"]["value"])
        ctx["unattributed"] = next(
            (t for t in detect["per_typology"] if t["typology"] == "UNATTRIBUTED"),
            {"recall": None},
        )
    decide = d.get("decide")
    if decide:
        runs = decide["coverage"]["by_alpha"]["0.05"]
        ctx["static"] = runs["static_pooled"]["overall"]
        ctx["aci"] = runs["aci_pooled"]["overall"]
    ctx["need_max"] = _max_analysts_needed(m)
    return ctx


def _max_analysts_needed(m: dict[str, Any]) -> str:
    decide = m["datasets"][m["primary_dataset"]].get("decide") or {}
    value = (decide.get("staffing") or {}).get("max_analysts_needed")
    return f"{value:,}" if isinstance(value, int) else "—"


def render_readme_block(m: dict[str, Any]) -> str:
    return _env().from_string(README_BLOCK).render(**_context(m)).strip() + "\n"


def render_model_card(m: dict[str, Any]) -> str:
    return _env().from_string(MODEL_CARD).render(**_context(m)).strip() + "\n"


def render_eval_report(m: dict[str, Any]) -> str:
    return (
        re.sub(r"\n{3,}", "\n\n", _env().from_string(EVAL_REPORT).render(**_context(m))).strip()
        + "\n"
    )


def splice_readme(readme: str, block: str) -> str:
    if START not in readme or END not in readme:
        msg = "README has no metrics markers"
        raise ValueError(msg)
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{block}{END}{tail}"


def targets(root: Path = REPO_ROOT) -> dict[Path, str]:
    return {
        root / "README.md": "readme",
        root / "MODEL_CARD.md": "model_card",
        root / "reports" / "EVAL_REPORT.md": "eval_report",
    }


def rendered(m: dict[str, Any], root: Path = REPO_ROOT) -> dict[Path, str]:
    """What every generated document should contain, given the metrics."""
    readme_path = root / "README.md"
    return {
        readme_path: splice_readme(readme_path.read_text(encoding="utf-8"), render_readme_block(m)),
        root / "MODEL_CARD.md": render_model_card(m),
        root / "reports" / "EVAL_REPORT.md": render_eval_report(m),
    }
