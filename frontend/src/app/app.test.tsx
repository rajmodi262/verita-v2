import { screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";

import { safeNext } from "../routes/login/LoginPage";
import { ANALYST, json, mockApi, problem, renderAt } from "../test/utils";

import { makeQueryClient } from "./providers";

describe("routing and the auth gate", () => {
  it("shows the landing page without a session and makes no API call", async () => {
    const { fetchMock } = mockApi({});
    renderAt("/");
    expect(await screen.findByRole("heading", { level: 1 })).toHaveTextContent(
      "Every alert explained",
    );
    expect(screen.getByText(/generated by the pipeline/)).toBeInTheDocument();
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it("redirects to login when there is no session, keeping the destination", async () => {
    mockApi({ "GET /me": () => problem(401, "unauthenticated", "Authentication required") });
    const { router } = renderAt("/capacity?date=2022-09-01");
    await screen.findByRole("heading", { name: "Open the case file" });
    expect(router.state.location.pathname).toBe("/login");
    expect(router.state.location.search).toBe(
      `?next=${encodeURIComponent("/capacity?date=2022-09-01")}`,
    );
  });

  it("renders the workspace shell for a signed-in user", async () => {
    mockApi({ "GET /me": () => json(ANALYST) });
    renderAt("/evidence-room");
    const nav = await screen.findByRole("navigation", { name: "Primary" });
    expect(within(nav).getByRole("link", { name: "Evidence room" })).toHaveAttribute(
      "aria-current",
      "page",
    );
    expect(screen.getByText("priya")).toBeInTheDocument();
    expect(screen.getByText("Analyst")).toBeInTheDocument();
    expect(await screen.findByText("Arrives in M8")).toBeInTheDocument();
  });

  it("shows an error with the request ID when the session check fails", async () => {
    mockApi({ "GET /me": () => problem(500, "internal-error", "Internal server error") });
    renderAt("/evidence-room");
    const alert = await screen.findByRole("alert");
    expect(alert).toHaveTextContent("Internal server error");
    expect(alert).toHaveTextContent("req-1");
  });

  it("renders a not-found page for unknown paths", async () => {
    mockApi({});
    renderAt("/does-not-exist");
    expect(await screen.findByText("No such page")).toBeInTheDocument();
  });

  it.each(["/evidence-room"])("renders the %s placeholder", async (path) => {
    mockApi({ "GET /me": () => json(ANALYST) });
    renderAt(path);
    expect(await screen.findByText(/Arrives in M\d/)).toBeInTheDocument();
  });
});

describe("login", () => {
  it("signs in and continues to the requested page", async () => {
    const user = userEvent.setup();
    let signedIn = false;
    const { calls } = mockApi({
      "GET /me": () =>
        signedIn ? json(ANALYST) : problem(401, "unauthenticated", "Authentication required"),
      "POST /auth/login": () => {
        signedIn = true;
        return json({ user: ANALYST, csrf_token: "csrf-1", expires_at: "2026-10-20T00:00:00Z" });
      },
    });
    const { router } = renderAt("/login?next=%2Fcases");
    const submit = await screen.findByRole("button", { name: "Sign in" });
    expect(submit).toBeDisabled();
    await user.type(screen.getByLabelText("Username"), "priya");
    await user.type(screen.getByLabelText("Password"), "correct-horse-battery");
    await user.click(submit);
    await waitFor(() => {
      expect(router.state.location.pathname).toBe("/cases");
    });
    const sent = calls.find((c) => c.key === "POST /auth/login")!.init.body;
    expect(typeof sent).toBe("string");
    const body: unknown = JSON.parse(sent as string);
    expect(body).toEqual({ username: "priya", password: "correct-horse-battery" });
  });

  it("explains a failed login without revealing whether the user exists", async () => {
    const user = userEvent.setup();
    mockApi({
      "GET /me": () => problem(401, "unauthenticated", "Authentication required"),
      "POST /auth/login": () => problem(401, "invalid-credentials", "Invalid username or password"),
    });
    renderAt("/login");
    await user.type(await screen.findByLabelText("Username"), "ghost");
    await user.type(screen.getByLabelText("Password"), "whatever-password");
    await user.click(screen.getByRole("button", { name: "Sign in" }));
    expect(await screen.findByRole("alert")).toHaveTextContent("don't match");
  });

  it("shows other server errors as they are", async () => {
    const user = userEvent.setup();
    mockApi({
      "GET /me": () => problem(401, "unauthenticated", "Authentication required"),
      "POST /auth/login": () => problem(429, "rate-limited", "Too many requests"),
    });
    renderAt("/login");
    await user.type(await screen.findByLabelText("Username"), "priya");
    await user.type(screen.getByLabelText("Password"), "whatever-password");
    await user.click(screen.getByRole("button", { name: "Sign in" }));
    expect(await screen.findByRole("alert")).toHaveTextContent("Too many requests");
  });

  it("sends an already signed-in user straight on", async () => {
    mockApi({ "GET /me": () => json(ANALYST) });
    const { router } = renderAt("/login");
    await waitFor(() => {
      expect(router.state.location.pathname).toBe("/queue");
    });
  });

  it.each([
    [null, "/queue"],
    ["/cases", "/cases"],
    ["https://evil.example", "/queue"],
    ["//evil.example", "/queue"],
    ["/\\evil.example", "/queue"],
  ])("safeNext(%s) → %s", (raw, expected) => {
    expect(safeNext(raw)).toBe(expected);
  });
});

describe("shell actions", () => {
  it("signs out with the CSRF token and returns to login", async () => {
    const user = userEvent.setup();
    let signedIn = true;
    document.cookie = "verita_csrf=csrf-from-cookie; path=/";
    const { calls } = mockApi({
      "GET /me": () =>
        signedIn ? json(ANALYST) : problem(401, "unauthenticated", "Authentication required"),
      "POST /auth/logout": () => {
        signedIn = false;
        return new Response(null, { status: 204 });
      },
    });
    const { router } = renderAt("/evidence-room");
    await user.click(await screen.findByRole("button", { name: "Sign out" }));
    await waitFor(() => {
      expect(router.state.location.pathname).toBe("/login");
    });
    const headers = calls.find((c) => c.key === "POST /auth/logout")!.init.headers as Record<
      string,
      string
    >;
    expect(headers["X-CSRF-Token"]).toBe("csrf-from-cookie");
  });

  it("toggles the theme and remembers it", async () => {
    const user = userEvent.setup();
    mockApi({ "GET /me": () => json(ANALYST) });
    renderAt("/evidence-room");
    const toggle = await screen.findByRole("button", { name: "Switch to night theme" });
    await user.click(toggle);
    expect(document.documentElement.dataset.theme).toBe("night");
    expect(localStorage.getItem("verita.theme")).toBe("night");
    await user.click(screen.getByRole("button", { name: "Switch to paper theme" }));
    expect(document.documentElement.dataset.theme).toBe("paper");
  });
});

describe("query retry policy", () => {
  it("never retries client errors, retries server errors twice", async () => {
    const { ApiError } = await import("../api/client");
    const retry = makeQueryClient().getDefaultOptions().queries?.retry as (
      n: number,
      e: unknown,
    ) => boolean;
    expect(retry(0, new ApiError({ status: 404, type: "x", title: "x" }))).toBe(false);
    expect(retry(0, new ApiError({ status: 503, type: "x", title: "x" }))).toBe(true);
    expect(retry(2, new ApiError({ status: 503, type: "x", title: "x" }))).toBe(false);
  });
});
